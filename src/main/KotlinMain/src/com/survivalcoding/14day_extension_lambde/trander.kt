package com.survivalcoding.`14day_extension_lambde`

// 1. 거래자 정보를 담는 클래스
data class Trader(
    val name: String, // 거래자 이름
    val city: String  // 근무하는 도시
)

// 2. 거래 내역 정보를 담는 클래스
data class Transaction(
    val trader: Trader, // 거래를 진행한 거래자 객체
    val year: Int,      // 거래 연도
    val value: Int      // 거래 금액
)

fun main() {
    // 기본 거래 데이터 목록 준비
    val transactions = listOf(
        Transaction(Trader("Brian", "Cambridge"), 2011, 300),
        Transaction(Trader("Raoul", "Cambridge"), 2012, 1000),
        Transaction(Trader("Raoul", "Cambridge"), 2011, 400),
        Transaction(Trader("Mario", "Milan"), 2012, 710),
        Transaction(Trader("Mario", "Milan"), 2012, 700),
        Transaction(Trader("Alan", "Cambridge"), 2012, 950)
    )

    // -------------------------------------------------------------------------
    // 1. 2011년에 일어난 모든 트랜잭션을 찾아 가격 기준 오름차순으로 정리하여 이름을 나열하시오
    // -------------------------------------------------------------------------
    val q1 = transactions
        .filter { it.year == 2011 }              // 2011년도에 일어난 거래만 쏙 골라냄 (filter 고계 함수)
        .sortedBy { it.value }                   // 거래 가격(value)을 기준으로 오름차순 정렬
        .map { it.trader.name }                  // 거래자 이름만 쏙 뽑아서 새로운 리스트로 변환 (map 고계 함수)

    println("1. 2011년 거래자 이름 (가격순): $q1")


    // -------------------------------------------------------------------------
    // 2. 거래자가 근무하는 모든 도시를 중복 없이 나열하시오
    // -------------------------------------------------------------------------
    val q2 = transactions
        .map { it.trader.city }                  // 모든 거래자의 도시 이름만 쏙 뽑아냄
        .distinct()                              // 중복되는 도시 이름은 싹 제거함

    println("2. 중복 없는 근무 도시 목록: $q2")


    // -------------------------------------------------------------------------
    // 3. 케임브리지에서 근무하는 모든 거래자를 찾아서 이름순으로 정렬하여 나열하시오
    // -------------------------------------------------------------------------
    val q3 = transactions
        .map { it.trader }                       // 거래자(Trader) 객체들만 쏙 뽑아냄
        .filter { it.city == "Cambridge" }       // 도시가 "Cambridge"인 사람들만 골라냄
        .distinct()                              // 혹시 모를 중복 거래자 제거
        .sortedBy { it.name }                    // 이름(name) 알파벳 순서대로 정렬

    println("3. 케임브리지 근무 거래자 (이름순): $q3")


    // -------------------------------------------------------------------------
    // 4. 모든 거래자의 이름을 알파벳순으로 정렬하여 나열하시오
    // -------------------------------------------------------------------------
    val q4 = transactions
        .map { it.trader.name }                  // 모든 거래자의 이름을 뽑아냄
        .distinct()                              // 중복 이름 제거
        .sorted()                                // 알파벳 순서대로 착착 정렬

    println("4. 전체 거래자 이름 (알파벳순): $q4")


    // -------------------------------------------------------------------------
    // 5. 밀라노에 거래자가 있는가?
    // -------------------------------------------------------------------------
    val q5 = transactions
        .any { it.trader.city == "Milan" }       // 도시가 "Milan"인 거래자가 단 한 명이라도 있는지 검사 (참/거짓 리턴)

    println("5. 밀라노에 거래자가 있는가?: $q5")


    // -------------------------------------------------------------------------
    // 6. 케임브리지에 거주하는 거래자의 모든 트랜잭션값을 출력하시오
    // -------------------------------------------------------------------------
    val q6 = transactions
        .filter { it.trader.city == "Cambridge" } // 케임브리지 거주 거래자의 거래만 골라냄
        .map { it.value }                         // 거래 금액(value)만 쏙 뽑아냄

    println("6. 케임브리지 거주자의 거래 금액들: $q6")


    // -------------------------------------------------------------------------
    // 7. 전체 트랜잭션 중 최대값은 얼마인가?
    // -------------------------------------------------------------------------
    // maxOfOrNull을 사용하여 안전하게 최댓값을 구하고, 만약 데이터가 없으면 0을 반환(엘비스 연산자 ?:)
    val q7 = transactions.maxOfOrNull { it.value } ?: 0

    println("7. 전체 트랜잭션 최댓값: $q7")


    // -------------------------------------------------------------------------
    // 8. 전체 트랜잭션 중 최소값은 얼마인가?
    // -------------------------------------------------------------------------
    // minOfOrNull을 사용하여 안전하게 최솟값을 구함
    val q8 = transactions.minOfOrNull { it.value } ?: 0

    println("8. 전체 트랜잭션 최솟값: $q8")
}